import { chromium } from "playwright";
import fs from "node:fs";
import path from "node:path";
const IMG = path.resolve("dist/logo.png");
const b = await chromium.launch({ headless: true, channel: "chrome" });
const ctx = await b.newContext({ acceptDownloads: true });
const p = await ctx.newPage();
await p.goto("http://127.0.0.1:3000/tools/product-design/new-designer", { waitUntil: "domcontentloaded" });
await p.waitForTimeout(2000);
await p.locator('input[type="file"][accept*="image/png"]').first().setInputFiles(IMG);
await p.waitForTimeout(3000);
await p.locator('[data-testid="designer-export"]').click();
await p.waitForTimeout(7000);
const dump = async (tag) => {
  const r = await p.evaluate(() => {
    const k = Object.keys(localStorage).find((x) => x.startsWith("tool-task:v1:task-"));
    const t = k ? JSON.parse(localStorage.getItem(k)) : null;
    const it = t?.result?.items?.[0];
    return it ? { url: (it.url || "").slice(0, 50), storageKey: it.storageKey || null, payloadDropped: it.payloadDropped ?? null, bytes: it.bytes } : null;
  });
  console.log(tag, JSON.stringify(r));
};
await dump("before reload:");
await p.reload({ waitUntil: "domcontentloaded" });
await p.waitForTimeout(4000);
await dump("after reload:");
await p.locator('[data-testid="tool-history-dock-toggle"]').first().click();
await p.waitForTimeout(1200);
const fb = async () => ((await p.locator('[data-testid="tool-history-dock-feedback"]').innerText().catch(() => "")) || "").trim();
await p.locator('[data-testid="tool-history-dock-save"]').first().click();
await p.waitForTimeout(3000);
console.log("save:", await fb());
await p.locator('[data-testid="tool-history-dock-canvas"]').first().click();
await p.waitForTimeout(4000);
console.log("canvas:", await fb());
const img = await p.evaluate(() => { const i = document.querySelector('[data-testid="tool-history-dock-result"] img'); return i ? { src: i.src.slice(0, 50), w: i.naturalWidth } : null; });
console.log("thumb:", JSON.stringify(img));
await p.screenshot({ path: "temp/designer-persist-evidence/09-actions-fixed.png" });
await b.close();
